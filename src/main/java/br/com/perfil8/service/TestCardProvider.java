    @Override
    public Card createCard(Difficulty difficulty, Set<String> excludedAnswers) {
        List<Card> available = cards.stream()
                .filter(card -> card.difficulty() == difficulty)
                .filter(card -> !excludedAnswers.contains(card.answer()))
                .toList();
        if (available.isEmpty()) {
            throw new IllegalStateException("Não há mais cartas de teste disponíveis para esta dificuldade.");
        }
        return available.get(ThreadLocalRandom.current().nextInt(available.size()));
    }

    private static Card card(Difficulty difficulty, Category category, String answer,
                             Set<String> aliases, String... clues) {
        return new Card(answer, category, difficulty, List.of(clues), aliases);
    }
